class Command(BaseCommand):
    help = "Создаёт демонстрационную редакционную ленту DearEditors."

    def handle(self, *args, **options):
        for item in DEMO_ARTICLES:
            slug = item["slug"]
            defaults = {**item, "status": Article.Status.PUBLISHED}
            defaults.pop("slug")
            Article.objects.update_or_create(slug=slug, defaults=defaults)

        self.stdout.write(self.style.SUCCESS(f"Демонстрационная лента готова: {len(DEMO_ARTICLES)} публикации."))
